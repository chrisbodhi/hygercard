// §5.1: `content_hash` is "sha256:" + hex(SHA-256(content_md as UTF-8)).
//
// Hand-rolled and synchronous on purpose. `crypto.subtle` is async and is
// undefined on an insecure origin, which is exactly where the iPad reaches the
// dev server (http://<lan-ip>:5173). The tests cross-check against node:crypto.

